#!/usr/bin/env python3
"""Generate LEADERBOARD.md, RUBRIC.md and the 50 cards in niches/ from the data files.

Usage:
    python3 tools/build_docs.py            write the generated files
    python3 tools/build_docs.py --check    report any generated file that is out of date, change nothing
"""

from __future__ import annotations

import pathlib
import sys
from typing import Any, Dict, List, Mapping

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import niche_lib as lib  # noqa: E402

GENERATED_LINE = "This file is generated by tools/build_docs.py from data/. Change the data, then run that tool."
SHORT_NAMES = ("No team", "Value", "Find", "Email", "Steady", "Rules", "Quiet")


def card_path(niche: Mapping[str, Any]) -> str:
    return f"niches/{niche['id']:02d}-{niche['slug']}.md"


def ordered(niches: List[Mapping[str, Any]]) -> List[Mapping[str, Any]]:
    return sorted(niches, key=lambda n: (-n["total"], n["name"]))


def render_card(niche: Mapping[str, Any], rank_number: int, rubric: Mapping[str, Any]) -> str:
    geo = rubric["fit_rules"]["geo"][niche["geo"]]["label"]
    regulated = f"Regulated: {niche['regulated']}" if niche["regulated"] else "Not in a regulated group"
    lines = [
        f"# {niche['name']}", "",
        f"**Default rank {rank_number} of 50. Total {niche['total']} out of 100.** {niche['category']}. {regulated}. {geo}.", "",
        lib.NOTE.replace("RUBRIC.md", "[RUBRIC.md](../RUBRIC.md)"), "",
        lib.niche_body(niche, rubric),
        "Before you send anything, read [the sending rules](../docs/SENDING-RULES.md) and [the honest limits](../HONEST-LIMITS.md).", "",
    ]
    return "\n".join(lines)


def render_leaderboard(niches: List[Mapping[str, Any]], rubric: Mapping[str, Any]) -> str:
    lines = [
        "# Leaderboard: 50 AI SDR niches, ranked", "",
        f"These are judgment scores against the published [rubric](RUBRIC.md). They are not market data, and a high rank does not promise results. {GENERATED_LINE}", "",
        "To re rank these for your own experience and country, run `python3 tools/rank.py --know trades --country US`, or use the [quick start prompt](QUICK-START-PROMPT.md).", "",
        "Column key: " + "; ".join(f"{short} = {crit['name']}" for short, crit in zip(SHORT_NAMES, rubric["criteria"])) + ". Every column is 1 to 5, and higher is always better for you.", "",
        "| Rank | Niche | Total | " + " | ".join(SHORT_NAMES) + " | Regulated |",
        "| --- | --- | --- | " + " | ".join("---" for _ in SHORT_NAMES) + " | --- |",
    ]
    for index, niche in enumerate(ordered(niches), 1):
        cells = " | ".join(str(niche["scores"][crit["key"]]) for crit in rubric["criteria"])
        lines.append(f"| {index} | [{niche['name']}]({card_path(niche)}) | {niche['total']} | {cells} | {niche['regulated'] or 'no'} |")
    lines.append("")
    return "\n".join(lines)


def render_rubric(rubric: Mapping[str, Any]) -> str:
    lines = [
        "# The scoring rubric", "",
        f"{rubric['note']} One person scored all 50 using these written rules, so you can disagree with any score and change it. {GENERATED_LINE}", "",
        "## How the total works", "",
        "Each niche gets a score from 1 to 5 on each of the 7 criteria. Each score is multiplied by the weight, and the results are added up. The weights add up to 20, so the lowest possible total is 20 and the highest is 100.", "",
        "| Criterion | Key | Weight |", "| --- | --- | --- |",
    ]
    lines += [f"| {c['name']} | `{c['key']}` | {c['weight']} |" for c in rubric["criteria"]]
    lines += ["", "## What each score means", ""]
    for crit in rubric["criteria"]:
        lines += [f"### {crit['name']}", "", crit["question"], ""]
        lines += [f"- **{level}:** {crit['anchors'][level]}" for level in ("1", "3", "5")]
        lines += ["- **2 and 4** sit between those.", ""]
    rules = rubric["fit_rules"]
    lines += [
        "## How your own fit score works", "",
        "`tools/rank.py` starts with the base score, using your weights, and scales it to 100. Then it adjusts for you:", "",
        f"- **Experience:** one matching experience tag adds {rules['experience_bonus_one_tag']} points. Two or more add {rules['experience_bonus_two_or_more_tags']}. This is on purpose: knowing a niche well is the whole idea of this kit.",
        "- **Country:** use the country your customers are in. If that is outside the US, a niche marked US first loses 10 points and a niche marked US only is left out, with the reason printed.",
        "- **Your own overrides:** you can change any single score for any niche in a profile file, and you must write the reason.", "",
        "Because experience is added on top of a score out of 100, your fit score can go above 100. That is expected.", "",
    ]
    return "\n".join(lines)


def expected_files() -> Dict[pathlib.Path, str]:
    rubric = lib.load_rubric()
    niches = lib.load_niches()
    files = {lib.ROOT / "LEADERBOARD.md": render_leaderboard(niches, rubric), lib.ROOT / "RUBRIC.md": render_rubric(rubric)}
    for index, niche in enumerate(ordered(niches), 1):
        files[lib.ROOT / card_path(niche)] = render_card(niche, index, rubric)
    return files


def main(argv: List[str]) -> int:
    files = expected_files()
    if "--check" in argv:
        stale = [str(path.relative_to(lib.ROOT)) for path, text in files.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        cards_on_disk = {p for p in (lib.ROOT / "niches").glob("*.md")} if (lib.ROOT / "niches").is_dir() else set()
        extra = [str(p.relative_to(lib.ROOT)) for p in sorted(cards_on_disk - set(files))]
        if stale or extra:
            print("Out of date: " + ", ".join(stale + extra))
            return 1
        print(f"All {len(files)} generated files match the data.")
        return 0
    (lib.ROOT / "niches").mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"Wrote {len(files)} files.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except lib.KitError as exc:
        print(f"Problem: {exc}", file=sys.stderr)
        sys.exit(2)
